# Shared helpers for the Superset lifecycle scripts. Sourced, not executed.
#
# Port allocation: each workspace reserves a block of PORT_BLOCK ports
# (e.g. 3110-3119). The dev server uses the first port; the rest are free for
# databases, APIs, etc. Reservations live in one machine-wide file so that
# workspaces of different projects never collide either.

WORKSPACE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKSPACE_ENV="$WORKSPACE_DIR/.superset/workspace.env"

PORT_START="${SUPERSET_PORT_START:-3100}"
PORT_BLOCK="${SUPERSET_PORT_BLOCK:-10}"
PORT_BLOCKS=100
ALLOC_FILE="${SUPERSET_HOME_DIR:-$HOME/.superset}/port-allocations.tsv"
LOCK_DIR="$ALLOC_FILE.lock"

log() { printf '\033[1;34m[superset]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[superset]\033[0m %s\n' "$*" >&2; exit 1; }

# mkdir is atomic everywhere (flock is missing on macOS).
_lock() {
  mkdir -p "$(dirname "$ALLOC_FILE")"
  local tries=0
  until mkdir "$LOCK_DIR" 2>/dev/null; do
    tries=$((tries + 1))
    # A lock older than ~10s was left behind by a killed script.
    if [ "$tries" -ge 100 ]; then rmdir "$LOCK_DIR" 2>/dev/null; tries=0; fi
    sleep 0.1
  done
  trap '_unlock' EXIT
}
_unlock() { rmdir "$LOCK_DIR" 2>/dev/null || true; trap - EXIT; }

_port_listening() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

_block_listening() {
  local p
  for ((p = $1; p < $1 + PORT_BLOCK; p++)); do
    _port_listening "$p" && return 0
  done
  return 1
}

# Prints this workspace's base port, reserving a free block if needed.
allocate_port() {
  _lock
  touch "$ALLOC_FILE"

  # Drop reservations whose workspace has been deleted without teardown.
  local tmp="$ALLOC_FILE.tmp.$$" base path
  while IFS=$'\t' read -r base path; do
    [ -n "$path" ] && [ -d "$path" ] && printf '%s\t%s\n' "$base" "$path"
  done <"$ALLOC_FILE" >"$tmp"
  mv "$tmp" "$ALLOC_FILE"

  base="$(awk -F'\t' -v p="$WORKSPACE_DIR" '$2 == p { print $1; exit }' "$ALLOC_FILE")"
  if [ -z "$base" ]; then
    local i candidate
    for ((i = 0; i < PORT_BLOCKS; i++)); do
      candidate=$((PORT_START + i * PORT_BLOCK))
      awk -F'\t' -v b="$candidate" '$1 == b { found = 1 } END { exit !found }' "$ALLOC_FILE" && continue
      _block_listening "$candidate" && continue
      base="$candidate"
      printf '%s\t%s\n' "$base" "$WORKSPACE_DIR" >>"$ALLOC_FILE"
      break
    done
  fi
  _unlock

  [ -n "$base" ] || die "No free port block between $PORT_START and $((PORT_START + PORT_BLOCKS * PORT_BLOCK))"
  echo "$base"
}

release_port() {
  [ -f "$ALLOC_FILE" ] || return 0
  _lock
  local tmp="$ALLOC_FILE.tmp.$$"
  awk -F'\t' -v p="$WORKSPACE_DIR" '$2 != p' "$ALLOC_FILE" >"$tmp"
  mv "$tmp" "$ALLOC_FILE"
  _unlock
}

compose_project_name() {
  basename "$WORKSPACE_DIR" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_\n-' '-'
}

# Writes .superset/workspace.env (gitignored) and exports its variables.
write_workspace_env() {
  local base="$1"
  cat >"$WORKSPACE_ENV" <<EOF
# Generated by .superset/setup.sh. Ports $base-$((base + PORT_BLOCK - 1)) are reserved for this workspace.
PORT=$base
SUPERSET_PORT_BASE=$base
COMPOSE_PROJECT_NAME=$(compose_project_name)
EOF
}

load_workspace_env() {
  if [ ! -f "$WORKSPACE_ENV" ]; then
    local base
    base="$(allocate_port)"
    write_workspace_env "$base"
  fi
  set -a
  # shellcheck source=/dev/null
  . "$WORKSPACE_ENV"
  set +a
}

compose_file() {
  local f
  for f in compose.yaml compose.yml docker-compose.yaml docker-compose.yml; do
    [ -f "$WORKSPACE_DIR/$f" ] && { echo "$f"; return 0; }
  done
  return 1
}

node_pm() {
  local d="$WORKSPACE_DIR"
  if [ -f "$d/bun.lock" ] || [ -f "$d/bun.lockb" ]; then echo bun
  elif [ -f "$d/pnpm-lock.yaml" ]; then echo pnpm
  elif [ -f "$d/yarn.lock" ]; then echo yarn
  else echo npm
  fi
}

# Prints the body of a package.json script, or nothing if it doesn't exist.
pkg_script() {
  node -e 'const s=(require(process.argv[1]).scripts||{})[process.argv[2]]; if (s) console.log(s)' \
    "$WORKSPACE_DIR/package.json" "$1" 2>/dev/null
}
